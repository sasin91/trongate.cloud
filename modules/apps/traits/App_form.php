<?php

require_once APPPATH . 'modules/platform/manifests/Manifests.php';

/**
 * New-app form shared by onboarding and the apps module:
 * repository picker data, validation rules/callbacks and app creation.
 * Repositories come from the current customer's GitHub token; the app goes
 * into the project the controller authorized.
 *
 * The using controller must also use Customer_guard and Provider_clients, and
 * its model must use Current_customer, Platform_actions and App_records.
 *
 * @property-read Validation $validation
 */
trait App_form {

    /** app.type values */
    const APP_TYPES = [
        'trongate_v2' => 'Trongate v2',
        'trongate_v1' => 'Trongate v1',
    ];

    /** The project the new app goes into, for the quota check (0: a project yet to be created) */
    private int $new_app_project_id = 0;

    /** The app whose settings are being saved, so its own domain does not count as taken */
    private int $editing_app_id = 0;

    /**
     * View data for the repository picker, or false when the customer has not connected a source provider yet.
     */
    function _app_form_data(int $customer_id): array|false {
        $provider = $this->_customer_provider($customer_id, 'source');

        if ($provider === false) {
            return false;
        }

        return [
            'provider' => $provider,
            'repositories' => $this->_provider_client($customer_id, $provider)->list_repositories(),
            'app_types' => self::APP_TYPES,
        ];
    }

    /**
     * @param int $project_id The target project (0 when onboarding creates it after validation)
     */
    function _set_app_rules(int $project_id): void {
        $this->new_app_project_id = $project_id;

        $this->validation->set_rules('provider', 'Source Control Provider', 'required|callback__validate_source_provider');
        $this->validation->set_rules('repository', 'Repository', 'required|max_length[200]|callback__validate_repository');
        $this->validation->set_rules('repository_branch', 'Branch', 'required|max_length[100]|callback__validate_branch');
        $this->validation->set_rules('label', 'App Name', 'required|min_length[3]|max_length[50]|callback__validate_project_has_room');
        $this->validation->set_rules('domain', 'Custom Domain', 'max_length[253]|callback__validate_domain');
        $this->validation->set_rules('type', 'App Type', 'required|callback__validate_app_type');
    }

    /**
     * Create the app from the validated POST data.
     * Slug and webhook secret are generated by App_records::create_app().
     */
    function _create_app_from_post(int $project_id, int $customer_id): int|false {
        $provider = post('provider', true);

        $client = $this->_provider_client($customer_id, $provider);

        return $this->model->create_app(
            project_id: $project_id,
            source_customer_id: $customer_id,
            label: post('label', true),
            type: post('type', true),
            source_url: $client->url(post('repository', true)),
            source_provider: $provider,
            source_branch: post('repository_branch', true),
            domain: $this->_normalise_domain(post('domain', true)),
            // The switch posts a hidden 0 then the checkbox's 1; older forms leave it out
            auto_deploy: !isset($_POST['auto_deploy']) || post('auto_deploy') === '1',
        );
    }

    /**
     * Queue the first deployment of a new app. A failure to queue never
     * blocks app creation; the customer can press Deploy later.
     */
    function _queue_first_deploy(int $customer_id, int $app_id): int|false {
        $app = $this->model->find_member_app($customer_id, $app_id);

        if ($app === false) {
            return false;
        }

        try {
            return $this->model->queue_deploy(
                (int) $app->project_id,
                $app_id,
                $customer_id,
                'manual'
            );
        } catch (RuntimeException $e) {
            return false;
        }
    }

    /**
     * MX partial: <option>s for the branches of a repository.
     */
    function repository_branch_options(): void {
        $this->_make_sure_allowed();
        $customer = $this->_customer_or_redirect();
        $repository = trim($_GET['repository'] ?? '');
        $provider = trim($_GET['provider'] ?? '');

        if ($this->_validate_source_provider($provider) !== true || $this->_validate_repository($repository) !== true) {
            http_response_code(422);
            die();
        }

        $client = $this->_provider_client((int) $customer->id, $provider);
        $branches = $client->list_branches($repository, 100);

        header('Content-Type: text/html');
        require APPPATH . 'modules/apps/views/_repository_branch_options.php';
    }

    /**
     * Hosts (with all their subdomains) an app may never claim: the control
     * panel (BASE_URL) and the image registry (PLATFORM_REGISTRY).
     *
     * @return list<string>
     */
    function _platform_hosts(): array {
        $hosts = [
            (string) parse_url(BASE_URL, PHP_URL_HOST),
            (string) parse_url('https://' . PLATFORM_REGISTRY, PHP_URL_HOST),
        ];

        return array_values(array_unique(array_filter(array_map('strtolower', $hosts))));
    }

    function _normalise_domain(string $domain): ?string {
        $domain = rtrim(strtolower(trim($domain)), '.');

        return $domain === '' ? null : $domain;
    }

    // --- Validation callbacks ---

    function _validate_repository(string $repository): bool|string {
        if (!preg_match('#^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$#', $repository)) {
            return 'Please choose a repository.';
        }

        return true;
    }

    function _validate_branch(string $branch): bool|string {
        if (!preg_match('#^[A-Za-z0-9._/-]+$#', $branch) || str_contains($branch, '..') || str_starts_with($branch, '-')) {
            return 'Invalid branch name.';
        }

        return true;
    }

    function _validate_app_type(string $type): bool|string {
        if (!isset(self::APP_TYPES[$type])) {
            return 'Invalid app type.';
        }

        return true;
    }

    /**
     * A new app starts on the default resource tier; the project's apps must
     * still fit its quota with it (Manifests::quota_shortfall), or its rollouts hang.
     */
    function _validate_project_has_room(string $label): bool|string {
        $tiers = $this->new_app_project_id > 0 ? $this->model->project_resource_tiers($this->new_app_project_id) : [];
        $tiers[] = Resource_tiers::DEFAULT_TIER;

        if (Manifests::quota_shortfall($tiers) !== null) {
            return 'This project has no room for another app. Make one of its apps smaller, or delete one, first.';
        }

        return true;
    }

    /**
     * Optional custom domain: a valid hostname, not a platform host and not verified by another app.
     * The app being edited ($editing_app_id) is ignored.
     */

    function _validate_domain(string $domain): bool|string {
        $domain = $this->_normalise_domain($domain);

        if ($domain === null) {
            return true;
        }

        $label = '[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?';
        if (!preg_match("/^({$label}\\.)+[a-z]{2,63}$/", $domain)) {
            return 'Please enter a valid domain, e.g. app.example.com.';
        }

        $apps_domain = strtolower(PLATFORM_APPS_DOMAIN);
        if ($domain === $apps_domain || str_ends_with($domain, '.' . $apps_domain)) {
            return 'Your app already gets a free ' . $apps_domain . ' address; enter your own domain here.';
        }

        foreach ($this->_platform_hosts() as $host) {
            if ($domain === $host || str_ends_with($domain, '.' . $host)) {
                return 'This domain belongs to the platform; enter your own domain.';
            }
        }

        if ($this->model->domain_taken($domain, $this->editing_app_id > 0 ? $this->editing_app_id : null)) {
            return 'This domain is already used by another app.';
        }

        return true;
    }
}
