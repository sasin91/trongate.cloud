<?php

require_once APPPATH . 'modules/platform/manifests/Manifests.php';

/**
 * New-project form shared by onboarding and the projects module:
 * repository picker data, validation rules/callbacks and project creation.
 *
 * The using controller must also use Customer_guard and Provider_clients, and
 * its model must use Current_customer, Platform_actions and Project_records.
 *
 * @property-read Validation $validation
 */
trait Project_form {

    /** project.type values */
    const PROJECT_TYPES = [
        'trongate_v2' => 'Trongate v2',
        'trongate_v1' => 'Trongate v1',
    ];

    /**
     * View data for the repository picker, or false when the team has no source provider yet.
     */
    function _project_form_data(int $team_id): array|false {
        $provider = $this->_team_provider($team_id, 'source');

        if ($provider === false) {
            return false;
        }

        return [
            'provider' => $provider,
            'repositories' => $this->_provider_client($team_id, $provider)->list_repositories(),
            'project_types' => self::PROJECT_TYPES,
        ];
    }

    function _set_project_rules(): void {
        $this->validation->set_rules('provider', 'Source Control Provider', 'required|callback__validate_source_provider');
        $this->validation->set_rules('repository', 'Repository', 'required|max_length[200]|callback__validate_repository');
        $this->validation->set_rules('repository_branch', 'Branch', 'required|max_length[100]|callback__validate_branch');
        $this->validation->set_rules('label', 'Project Name', 'required|min_length[3]|max_length[50]|callback__validate_team_has_room');
        $this->validation->set_rules('domain', 'Custom Domain', 'max_length[253]|callback__validate_domain');
        $this->validation->set_rules('type', 'Project Type', 'required|callback__validate_project_type');
    }

    /**
     * Create the project from the validated POST data.
     * Slug and webhook secret are generated by Project_records::create_project().
     */
    function _create_project_from_post(int $team_id): int|false {
        $provider = post('provider', true);

        $client = $this->_provider_client($team_id, $provider);

        return $this->model->create_project(
            team_id: $team_id,
            label: post('label', true),
            type: post('type', true),
            source_url: $client->url(post('repository', true)),
            source_provider: $provider,
            source_branch: post('repository_branch', true),
            domain: $this->_normalise_domain(post('domain', true)),
            // The switch posts a hidden 0 then the checkbox's 1; older forms leave it out
            auto_deploy: !isset($_POST['auto_deploy']) || post('auto_deploy') === '1',
        );
    }

    /**
     * Queue the first deployment of a new project. A failure to queue never
     * blocks project creation; the customer can press Deploy later.
     */
    function _queue_first_deploy(int $team_id, int $project_id): int|false {
        $customer = $this->model->_get_current_customer();
        $member = $this->model->get_current_team_member();

        try {
            return $this->model->queue_deploy(
                $team_id,
                $project_id,
                $member === false ? null : (int) $member->id,
                $customer === false ? null : (int) $customer->id,
                'manual'
            );
        } catch (RuntimeException $e) {
            return false;
        }
    }

    /**
     * MX partial: <option>s for the branches of a repository.
     */
    function repository_branch_options(): void {
        $this->_make_sure_allowed();
        $team_id = $this->_team_id_or_redirect();
        $repository = trim($_GET['repository'] ?? '');
        $provider = trim($_GET['provider'] ?? '');

        if ($this->_validate_source_provider($provider) !== true || $this->_validate_repository($repository) !== true) {
            http_response_code(422);
            die();
        }

        $client = $this->_provider_client($team_id, $provider);
        $branches = $client->list_branches($repository);

        header('Content-Type: text/html');
        require APPPATH . 'modules/projects/views/_repository_branch_options.php';
    }

    /**
     * Hosts (with all their subdomains) a project may never claim: the control
     * panel (BASE_URL) and the image registry (PLATFORM_REGISTRY).
     *
     * @return list<string>
     */
    function _platform_hosts(): array {
        $hosts = [
            (string) parse_url(BASE_URL, PHP_URL_HOST),
            (string) parse_url('https://' . PLATFORM_REGISTRY, PHP_URL_HOST),
        ];

        return array_values(array_unique(array_filter(array_map('strtolower', $hosts))));
    }

    function _normalise_domain(string $domain): ?string {
        $domain = rtrim(strtolower(trim($domain)), '.');

        return $domain === '' ? null : $domain;
    }

    // --- Validation callbacks ---

    function _validate_repository(string $repository): bool|string {
        if (!preg_match('#^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$#', $repository)) {
            return 'Please choose a repository.';
        }

        return true;
    }

    function _validate_branch(string $branch): bool|string {
        if (!preg_match('#^[A-Za-z0-9._/-]+$#', $branch) || str_contains($branch, '..') || str_starts_with($branch, '-')) {
            return 'Invalid branch name.';
        }

        return true;
    }

    function _validate_project_type(string $type): bool|string {
        if (!isset(self::PROJECT_TYPES[$type])) {
            return 'Invalid project type.';
        }

        return true;
    }

    /**
     * Optional custom domain: a valid hostname, not a platform host and not verified by another project.
     * The project being edited (segment 3 on projects/{id}/settings/submit) is ignored.
     */
    /**
     * A new project starts on the default resource tier; the team's apps must
     * still fit its quota with it (Manifests::quota_shortfall), or its rollouts hang.
     */
    function _validate_team_has_room(string $label): bool|string {
        $tiers = $this->model->team_resource_tiers($this->_team_id_or_redirect());
        $tiers[] = Resource_tiers::DEFAULT_TIER;

        if (Manifests::quota_shortfall($tiers) !== null) {
            return 'Your team has no room for another app. Make one of your apps smaller, or delete one, first.';
        }

        return true;
    }

    function _validate_domain(string $domain): bool|string {
        $domain = $this->_normalise_domain($domain);

        if ($domain === null) {
            return true;
        }

        $label = '[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?';
        if (!preg_match("/^({$label}\\.)+[a-z]{2,63}$/", $domain)) {
            return 'Please enter a valid domain, e.g. app.example.com.';
        }

        $apps_domain = strtolower(PLATFORM_APPS_DOMAIN);
        if ($domain === $apps_domain || str_ends_with($domain, '.' . $apps_domain)) {
            return 'Your app already gets a free ' . $apps_domain . ' address; enter your own domain here.';
        }

        foreach ($this->_platform_hosts() as $host) {
            if ($domain === $host || str_ends_with($domain, '.' . $host)) {
                return 'This domain belongs to the platform; enter your own domain.';
            }
        }

        $ignore_id = segment(3, 'int');
        if ($this->model->domain_taken($domain, $ignore_id > 0 ? $ignore_id : null)) {
            return 'This domain is already used by another project.';
        }

        return true;
    }
}
